"""提示词模板配置模块

定义不同模式的提示词模板，支持：
1. paper_summary: 论文总结和质询（默认模式）
2. research_proposal: 论文构思和方法设计路线图审查
3. experiment_design: 实验项目设计路线图审查
"""

from typing import Dict, Callable
from dataclasses import dataclass
from enum import Enum


class AnalysisMode(Enum):
    """分析模式枚举"""
    PAPER_SUMMARY = "paper_summary"
    RESEARCH_PROPOSAL = "research_proposal"
    EXPERIMENT_DESIGN = "experiment_design"


@dataclass
class PromptTemplate:
    """提示词模板类"""
    mode: AnalysisMode
    name: str
    description: str
    analyze_prompt: Callable[[str, str], str]
    debate_prompt: Callable[[str, str, str], str]
    respond_prompt: Callable[[str, str, str], str]


class PromptManager:
    """提示词管理器"""
    
    def __init__(self):
        self._templates: Dict[AnalysisMode, PromptTemplate] = {}
        self._register_default_templates()
    
    def _register_default_templates(self):
        """注册默认的提示词模板"""
        # 模式1: 论文总结和质询
        self.register_template(PromptTemplate(
            mode=AnalysisMode.PAPER_SUMMARY,
            name="论文总结和质询",
            description="对学术论文进行详细分析和总结，包括算法设计、创新性、实验结果等方面",
            analyze_prompt=self._paper_summary_analyze_prompt,
            debate_prompt=self._paper_summary_debate_prompt,
            respond_prompt=self._paper_summary_respond_prompt
        ))
        
        # 模式2: 论文构思和方法设计路线图审查
        self.register_template(PromptTemplate(
            mode=AnalysisMode.RESEARCH_PROPOSAL,
            name="论文构思和方法设计路线图审查",
            description="审查研究提案和方法设计路线图，评估研究思路的合理性和可行性",
            analyze_prompt=self._research_proposal_analyze_prompt,
            debate_prompt=self._research_proposal_debate_prompt,
            respond_prompt=self._research_proposal_respond_prompt
        ))
        
        # 模式3: 实验项目设计路线图审查
        self.register_template(PromptTemplate(
            mode=AnalysisMode.EXPERIMENT_DESIGN,
            name="实验项目设计路线图审查",
            description="审查实验项目设计，评估实验方案的科学性和可执行性",
            analyze_prompt=self._experiment_design_analyze_prompt,
            debate_prompt=self._experiment_design_debate_prompt,
            respond_prompt=self._experiment_design_respond_prompt
        ))
    
    def register_template(self, template: PromptTemplate):
        """注册新的提示词模板"""
        self._templates[template.mode] = template
    
    def get_template(self, mode: AnalysisMode) -> PromptTemplate:
        """获取指定模式的提示词模板"""
        if mode not in self._templates:
            raise ValueError(f"未找到模式: {mode}")
        return self._templates[mode]
    
    def list_modes(self) -> Dict[str, str]:
        """列出所有可用的模式"""
        return {
            mode.value: template.description 
            for mode, template in self._templates.items()
        }
    
